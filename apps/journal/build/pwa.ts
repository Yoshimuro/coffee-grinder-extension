import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';

import type { Plugin } from 'vite';

interface PrecacheAsset {
  path: string;
  integrity: string;
}

/** Include public files as well as Vite's hashed assets in the offline shell. */
async function publicFiles(directory: string, prefix = ''): Promise<[string, Uint8Array][]> {
  const files: [string, Uint8Array][] = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const name = `${prefix}${entry.name}`;
    if (entry.isDirectory()) files.push(...await publicFiles(join(directory, entry.name), `${name}/`));
    else if (entry.isFile()) files.push([name, await readFile(join(directory, entry.name))]);
  }
  return files;
}

export function serviceWorker(): Plugin {
  let publicDirectory = '';
  return {
    name: 'bj-service-worker',
    apply: 'build',
    enforce: 'post',
    configResolved(config) {
      publicDirectory = config.publicDir;
    },
    generateBundle: {
      // Vite must have emitted index.html before we hash its actual contents.
      order: 'post',
      async handler(_options, bundle) {
        const files = new Map<string, string | Uint8Array>();
        if (publicDirectory) {
          for (const [name, source] of await publicFiles(publicDirectory)) files.set(name, source);
        }
        for (const [name, output] of Object.entries(bundle)) {
          files.set(name, output.type === 'chunk' ? output.code : output.source);
        }
        if (!files.has('index.html')) this.error('The PWA shell requires index.html');

        // HTML, icons and manifest have stable names, so hashing names alone
        // would leave their updates permanently stuck in a cache-first shell.
        const hash = createHash('sha256').update(swSource('', []));
        const names = [...files.keys()].sort();
        for (const name of names) hash.update(name).update('\0').update(files.get(name)!).update('\0');
        const assets = names.map((name) => ({
          path: `./${name}`,
          integrity: `sha256-${createHash('sha256').update(files.get(name)!).digest('base64')}`,
        }));
        this.emitFile({
          type: 'asset',
          fileName: 'sw.js',
          source: swSource(hash.digest('hex').slice(0, 16), assets),
        });
      },
    },
  };
}

function swSource(version: string, assets: readonly PrecacheAsset[]): string {
  return `/* Generated by build/pwa.ts. */
const PREFIX = 'brew-journal:' + self.registration.scope + ':';
const CACHE = PREFIX + '${version}';
const ASSETS = ${JSON.stringify(assets, null, 2)}.map(({ path, integrity }) => ({
  url: new URL(path, self.registration.scope).href,
  integrity,
}));
const ASSET_URLS = new Set(ASSETS.map(({ url }) => url));
let precaching;

function precache() {
  // Share one recovery batch across concurrent requests. A failed attempt must
  // be retryable when connectivity returns, so reset the promise either way.
  if (!precaching) {
    precaching = (async () => {
      const cache = await caches.open(CACHE);
      // addAll commits atomically after every fetch succeeds. Never delete this
      // cache on failure: a rollback may reuse the active worker's version.
      // Integrity also keeps a newer index/manifest out of an older cache when
      // recovering after a deployment that changed these stable-name files.
      await cache.addAll(ASSETS.map(({ url, integrity }) => new Request(url, { cache: 'reload', integrity })));
      return cache;
    })().catch((error) => {
      // This handler belongs to the shared batch, not each waiting request.
      console.warn('[PWA] Failed to prepare offline cache', CACHE, error);
      throw error;
    }).finally(() => { precaching = undefined; });
  }
  return precaching;
}

self.addEventListener('install', (event) => {
  event.waitUntil(precache());
  // No skipWaiting: an open timer or form keeps its matching assets until
  // all tabs of the previous version close. First installs activate normally.
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE)
      .map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  const scope = new URL(self.registration.scope);
  if (request.method !== 'GET' || url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;

  const target = request.mode === 'navigate' ? new URL('index.html', scope).href : request;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(target);
    if (hit) return hit;

    if (request.mode === 'navigate' || ASSET_URLS.has(url.href)) {
      let restored;
      try {
        // Restore the full shell before serving a cache-missing navigation:
        // the next launch must work offline, including assets not rendered now.
        restored = await precache();
      } catch {
        // precache already logged the failure once. Keep online use available
        // without storing a mixed or partial shell.
        return fetch(request);
      }
      const response = await restored.match(target);
      if (response) return response;
    }
    return fetch(request);
  })());
});
`;
}
