/**
 * Выбор реализации: телефон или браузер.
 *
 * Правило одно и оно жёсткое: `@capacitor/core` — единственный пакет Capacitor,
 * который разрешено импортировать статически. Он крошечный (мост и определение
 * платформы) и сам по себе работает в вебе. Все остальные плагины подтягиваются
 * `import()` внутри `nativeOnly`, поэтому в браузерный бандл они не попадают —
 * Rollup выносит их отдельными чанками, а `isNative()` в вебе никогда не даёт
 * повода их загрузить.
 *
 * Реализация выбирается один раз и кешируется промисом: экраны зовут
 * `photos.capture()` десятки раз, и каждый такой вызов не должен превращаться в
 * повторный `import()`.
 */

import { Capacitor } from '@capacitor/core';

/** Мы внутри APK (или будущего ipa), а не во вкладке браузера. */
export function isNative(): boolean {
  try {
    return Capacitor.isNativePlatform();
  } catch {
    // Мост не поднялся — значит, точно не нативная платформа.
    return false;
  }
}

/**
 * Связывает веб-реализацию с нативной.
 *
 * Возвращает функцию-геттер, а не сам объект: `import()` асинхронен, а
 * интерфейсы платформенного слоя и так все до одного асинхронные.
 *
 * Если нативный модуль не загрузился (плагин не собран в этой сборке APK,
 * например), берётся веб-реализация. Молча: приложение обязано работать, а не
 * объяснять пользователю устройство своей сборки.
 */
export function bind<T>(web: () => T, native: () => Promise<T>): () => Promise<T> {
  let chosen: Promise<T> | null = null;

  return () => {
    chosen ??= isNative()
      ? native().catch(() => web())
      : Promise.resolve(web());
    return chosen;
  };
}
