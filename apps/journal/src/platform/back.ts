/**
 * Системная кнопка (или жест) «назад» — платформенный интерфейс.
 *
 * На Android «назад» — основной способ навигации, и без подписки Capacitor
 * отдаёт нажатие системе: приложение уходит в лаунчер с любого вложенного
 * экрана. Эмуляторный прогон BJ-7 поймал это на детали записи (баг 2): «←» в
 * шапке возвращал в журнал, системная «назад» — закрывала приложение.
 *
 * Решение о том, что значит нажатие, принимает навигация (`handleHardwareBack`
 * в `app/nav.ts`); здесь остаётся только подписка и «свернуть», если возвращать
 * некуда. Сворачиваем, а не выходим: `exitApp()` убивает процесс, и
 * недописанное заваривание пришлось бы поднимать из базы. `minimizeApp()`
 * оставляет приложение живым ровно там, где его бросили.
 *
 * В браузере функция не делает ничего: у вкладки своя история и своя кнопка
 * «назад», и перехватывать их приложению незачем.
 */

import { isNative } from './native.js';

/** Обработчик: `true` — приложение обработало «назад» само. */
export type BackHandler = () => boolean;

/**
 * Подписывает приложение на системную «назад». Вызывается один раз на старте.
 *
 * Ничего не ждёт и ничего не бросает: подписка — не то, ради чего стоит держать
 * первый кадр, а её отказ (плагин не собран в этой сборке APK) означает лишь
 * поведение по умолчанию, то есть ровно то, что было до этой правки.
 */
export function startBackButton(onBack: BackHandler): void {
  if (!isNative()) return;
  void import('./back.capacitor.js')
    .then((m) => m.listenBackButton(onBack))
    .catch(() => undefined);
}
