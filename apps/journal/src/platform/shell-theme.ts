/**
 * Тема нативной оболочки — платформенный интерфейс и веб-заглушка.
 *
 * Веб-слой красит себя сам: `data-theme` на `<html>` переключает токены, а
 * `<meta name="theme-color">` объясняет браузеру, чем красить его собственную
 * полоску. Но у APK поверх веб-слоя есть ещё три поверхности, до которых CSS не
 * дотягивается: статус-бар, панель навигации и — главное — стартовое окно,
 * которое система рисует ДО того, как выполнится хоть строка нашего кода.
 *
 * Стартовое окно и есть та причина, по которой этот интерфейс существует.
 * Победить его перекраской из JS нельзя в принципе: к моменту, когда JS
 * запускается, окно уже нарисовано. Единственный рычаг — попросить систему
 * запомнить выбранный приложением night mode, чтобы она сама выбрала нужные
 * ресурсы в следующий раз. Это `UiModeManager.setApplicationNightMode()`,
 * Android 12+; всё, что делает нативная часть, — вызывает его и раскладывает
 * ресурсы по `values/` и `values-night/`.
 *
 * В браузере всё это не нужно и заглушка пуста — не «не поддерживается», а
 * «уже сделано»: `theme-color` и `color-scheme` браузер читает сам.
 */

import type { ThemePref } from '../db/schema.js';

import { bind } from './native.js';

export interface ShellTheme {
  /**
   * Передаёт выбор в оболочку.
   *
   * Оба аргумента нужны, и подменять один другим нельзя: night mode системе
   * сообщается именно ВЫБОРОМ (`system` там — это «следуй за мной», отдельный
   * режим), а фон WebView — уже РАЗРЕШЁННЫМ цветом, потому что красить его
   * «системным» невозможно.
   *
   * Цвет приходит строкой, а не выводится здесь: таблица цветов — часть
   * веб-слоя (`ui/theme.ts`), и платформенному слою незачем её знать.
   */
  apply(pref: ThemePref, color: string): Promise<void>;
}

/** В браузере оболочки нет: её роль играют мета-теги и `color-scheme`. */
export function createWebShellTheme(): ShellTheme {
  return {
    async apply(): Promise<void> {
      /* пусто по существу, а не по недосмотру — см. шапку файла */
    },
  };
}

/* ── Реализация, которую видит приложение ────────────────────────────────── */

const shell = bind<ShellTheme>(createWebShellTheme, async () =>
  (await import('./shell-theme.capacitor.js')).createCapacitorShellTheme(),
);

export const shellTheme: ShellTheme = {
  apply: async (pref, color) => {
    await (await shell()).apply(pref, color);
  },
};
