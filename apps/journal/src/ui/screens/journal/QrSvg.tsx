/**
 * QR рецепта — настоящий, сканируемый.
 *
 * Прототип рисовал здесь шум (`qrSvg`, `DC:1131`), а BJ-4 убрал и его, и пустую
 * площадку под него (D-12): картинка, которая выглядит как QR и не сканируется,
 * хуже, чем её отсутствие. Здесь кодировщик настоящий — `uqr`, без зависимостей
 * и без сети, — и блок вернулся вместе с ним.
 *
 * Инверсия. QR читается по контрасту, а не по «чёрному на белом», но большинство
 * камер ждёт тёмные модули на светлом. Поэтому светлое поле здесь — не
 * оформление, а тихая зона кода.
 *
 * Из этого следует единственное исключение из правила «цвет берётся из
 * токенов»: два цвета ниже за темой НЕ идут (BJ-9). Их контраст адресован
 * камере, а не глазу, и перекрасить их по теме значит поменять шанс, что код
 * вообще прочитается, — на светлой теме площадка просто станет менее заметной
 * глазом, и это правильный размен.
 *
 * Уровень коррекции `M`: `L` экономит модули, но экран телефона снимают с руки
 * и под углом, а 15% восстановления — обычный компромисс для экранных кодов.
 */

import { encode } from 'uqr';

import { modulesPath } from './qr.js';

/* Не токены и не тема — см. шапку: это контраст для камеры. Значения совпадают
   с тёмной палитрой не по смыслу, а по совпадению: светлая тихая зона и почти
   чёрные модули. */
const QR_QUIET = '#ededeb';
const QR_MODULE = '#0c0c0c';
import './journal.css';

export interface QrSvgProps {
  /** Строка payload. Пустая не рисуется. */
  text: string;
  /**
   * Сторона в пикселях.
   *
   * 176 при типичной версии кода (45 модулей с рамкой) даёт около четырёх
   * логических пикселей на модуль — нижняя граница, на которой чужая камера
   * ещё уверенно берёт код с экрана.
   */
  size?: number;
}

export function QrSvg({ text, size = 176 }: QrSvgProps) {
  if (!text) return null;

  /* `border: 2` — тихая зона внутри самой матрицы: без неё светлое поле
     пришлось бы добивать вёрсткой, и любой отступ в CSS ломал бы распознавание. */
  const qr = encode(text, { ecc: 'M', border: 2 });

  return (
    <svg
      className="jr-qr__code"
      viewBox={`0 0 ${String(qr.size)} ${String(qr.size)}`}
      width={size}
      height={size}
      shapeRendering="crispEdges"
      // Содержимое дублируется соседними строками экрана; для скринридера
      // матрица — шум.
      aria-hidden="true"
      focusable="false"
    >
      <rect width={qr.size} height={qr.size} fill={QR_QUIET} />
      <path d={modulesPath(qr.data)} fill={QR_MODULE} />
    </svg>
  );
}
